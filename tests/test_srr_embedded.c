#include "srr_embedded.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <assert.h>

/* Mock loopback buffer for zero-heap test */
typedef struct {
    uint8_t buf[2048];
    size_t len;
} mock_tx_channel_t;

static int mock_tx(const uint8_t *data, size_t len, void *user_data) {
    mock_tx_channel_t *ch = (mock_tx_channel_t *)user_data;
    if (ch->len + len > sizeof(ch->buf)) return -1;
    memcpy(ch->buf + ch->len, data, len);
    ch->len += len;
    return 0;
}

/* Service 1: Device service */
#define SVC_DEVICE 1
#define OP_INFO    1

static int device_service_handler(
    uint16_t service_id,
    uint16_t operation_id,
    const uint8_t *req_payload,
    size_t req_len,
    uint8_t *reply_buf,
    size_t reply_cap,
    size_t *out_reply_len,
    void *user_data)
{
    (void)service_id;
    (void)req_payload;
    (void)req_len;
    (void)user_data;

    if (operation_id == OP_INFO) {
        const char *info = "SRR-MCU-RP2040-v1.0";
        size_t slen = strlen(info);
        if (reply_cap < slen) return -1;
        memcpy(reply_buf, info, slen);
        *out_reply_len = slen;
        return 0;
    }
    return -1; /* Unknown op */
}

/* Pulse test tracker */
static int g_pulse_received = 0;
static uint16_t g_pulse_svc = 0;
static uint16_t g_pulse_op = 0;

static void pulse_handler(
    uint16_t service_id,
    uint16_t operation_id,
    const uint8_t *payload,
    size_t len,
    void *user_data)
{
    (void)payload;
    (void)len;
    (void)user_data;
    g_pulse_received++;
    g_pulse_svc = service_id;
    g_pulse_op = operation_id;
}

static void test_embedded_service_dispatch(void) {
    printf("Testing embedded cooperative service dispatch...\n");

    /* Statically allocated buffers (Zero Heap Allocation) */
    static uint8_t rx_buf[512];
    static uint8_t decode_buf[512];
    static uint8_t tx_buf[512];
    static uint8_t server_reply_buf[512];

    mock_tx_channel_t server_tx = { .len = 0 };

    srr_endpoint_t ep;
    int rc = srr_endpoint_init(
        &ep, 0x12345678, mock_tx, &server_tx,
        rx_buf, sizeof(rx_buf),
        decode_buf, sizeof(decode_buf),
        tx_buf, sizeof(tx_buf),
        server_reply_buf, sizeof(server_reply_buf)
    );
    assert(rc == 0);

    rc = srr_endpoint_register_service(&ep, SVC_DEVICE, device_service_handler, NULL);
    assert(rc == 0);

    /* Construct a wire request frame as if sent by host */
    srr_wire_header_t req_hdr = {
        .magic = SRR_WIRE_MAGIC,
        .version = SRR_WIRE_VERSION,
        .msg_type = SRR_WIRE_REQUEST,
        .session_id = 0x12345678,
        .trans_id = 42,
        .service_id = SVC_DEVICE,
        .operation_id = OP_INFO,
        .payload_len = 0
    };

    uint8_t host_frame[256];
    size_t host_frame_len = srr_wire_encode_frame(&req_hdr, NULL, 0, host_frame, sizeof(host_frame));
    assert(host_frame_len > 0);

    /* Feed frame bytes into the embedded endpoint (1 byte at a time to test streaming parser) */
    for (size_t i = 0; i < host_frame_len; i++) {
        srr_endpoint_feed_byte(&ep, host_frame[i]);
    }

    assert(ep.rx_frames == 1);
    assert(ep.tx_frames == 1);
    assert(server_tx.len > 0);

    /* Verify the reply generated by the embedded endpoint */
    srr_wire_parser_t client_parser;
    static uint8_t cl_rx[512];
    static uint8_t cl_dec[512];
    srr_wire_parser_init(&client_parser, cl_rx, sizeof(cl_rx), cl_dec, sizeof(cl_dec));

    srr_wire_header_t reply_hdr;
    const uint8_t *reply_payload = NULL;
    srr_parser_status_t st = SRR_PARSER_NEED_MORE;

    for (size_t i = 0; i < server_tx.len; i++) {
        st = srr_wire_parser_feed_byte(&client_parser, server_tx.buf[i], &reply_hdr, &reply_payload);
    }
    assert(st == SRR_PARSER_FRAME_READY);
    assert(reply_hdr.msg_type == SRR_WIRE_REPLY);
    assert(reply_hdr.trans_id == 42);
    assert(reply_hdr.payload_len == strlen("SRR-MCU-RP2040-v1.0"));
    assert(memcmp(reply_payload, "SRR-MCU-RP2040-v1.0", reply_hdr.payload_len) == 0);

    printf("  Embedded service dispatch verified: RP2040 info reply matched.\n");
}

static void test_embedded_pulses(void) {
    printf("Testing embedded pulse generation and reception...\n");

    static uint8_t rx_buf[512], decode_buf[512], tx_buf[512], rep_buf[512];
    mock_tx_channel_t tx_chan = { .len = 0 };

    srr_endpoint_t ep;
    srr_endpoint_init(&ep, 0xABC, mock_tx, &tx_chan, rx_buf, sizeof(rx_buf), decode_buf, sizeof(decode_buf), tx_buf, sizeof(tx_buf), rep_buf, sizeof(rep_buf));

    srr_endpoint_register_pulse_handler(&ep, pulse_handler, NULL);

    /* 1. Device originates pulse */
    int rc = srr_endpoint_send_pulse(&ep, 10, 1, "INTERRUPT", 9);
    assert(rc == 0);
    assert(tx_chan.len > 0);

    /* 2. Host sends pulse into device */
    srr_wire_header_t pulse_hdr = {
        .magic = SRR_WIRE_MAGIC,
        .version = SRR_WIRE_VERSION,
        .msg_type = SRR_WIRE_PULSE,
        .session_id = 0xABC,
        .trans_id = 0,
        .service_id = 20,
        .operation_id = 2,
        .payload_len = 0
    };
    uint8_t pulse_frame[256];
    size_t flen = srr_wire_encode_frame(&pulse_hdr, NULL, 0, pulse_frame, sizeof(pulse_frame));
    assert(flen > 0);

    srr_endpoint_feed_bytes(&ep, pulse_frame, flen);
    assert(g_pulse_received == 1);
    assert(g_pulse_svc == 20);
    assert(g_pulse_op == 2);

    printf("  Embedded pulses verified successfully.\n");
}

static void test_embedded_async_client_and_timeouts(void) {
    printf("Testing embedded async client transactions & timeouts...\n");

    static uint8_t rx_buf[512], decode_buf[512], tx_buf[512], rep_buf[512];
    mock_tx_channel_t tx_chan = { .len = 0 };

    srr_endpoint_t ep;
    srr_endpoint_init(&ep, 0x1, mock_tx, &tx_chan, rx_buf, sizeof(rx_buf), decode_buf, sizeof(decode_buf), tx_buf, sizeof(tx_buf), rep_buf, sizeof(rep_buf));

    uint8_t client_reply_buf[64];
    uint32_t now_ms = 1000;

    /* Start async request */
    uint64_t tid = srr_begin_request(
        &ep, 1, 1, "PING", 4,
        client_reply_buf, sizeof(client_reply_buf),
        500, now_ms
    );
    assert(tid > 0);
    assert(srr_poll_transaction(&ep, tid) == SRR_TRANS_PENDING);

    /* Advance clock before timeout */
    now_ms += 200;
    srr_endpoint_tick(&ep, now_ms);
    assert(srr_poll_transaction(&ep, tid) == SRR_TRANS_PENDING);

    /* Feed incoming matching reply */
    srr_wire_header_t rep_hdr = {
        .magic = SRR_WIRE_MAGIC,
        .version = SRR_WIRE_VERSION,
        .msg_type = SRR_WIRE_REPLY,
        .session_id = 0x1,
        .trans_id = tid,
        .service_id = 1,
        .operation_id = 1,
        .payload_len = 4
    };
    uint8_t frame[256];
    size_t flen = srr_wire_encode_frame(&rep_hdr, "PONG", 4, frame, sizeof(frame));
    srr_endpoint_feed_bytes(&ep, frame, flen);

    assert(srr_poll_transaction(&ep, tid) == SRR_TRANS_REPLIED);

    size_t actual_len = 0;
    int err = 0;
    int rc = srr_collect_reply(&ep, tid, &actual_len, &err);
    assert(rc == 0);
    assert(actual_len == 4);
    assert(memcmp(client_reply_buf, "PONG", 4) == 0);

    /* Slot should now be freed */
    assert(srr_poll_transaction(&ep, tid) == SRR_TRANS_UNUSED);

    /* Test timeout */
    tx_chan.len = 0;
    uint64_t tid2 = srr_begin_request(
        &ep, 1, 1, "WAIT", 4,
        client_reply_buf, sizeof(client_reply_buf),
        300, now_ms
    );
    assert(tid2 > 0);
    assert(srr_poll_transaction(&ep, tid2) == SRR_TRANS_PENDING);

    /* Advance time past 300ms */
    now_ms += 400;
    srr_endpoint_tick(&ep, now_ms);
    assert(srr_poll_transaction(&ep, tid2) == SRR_TRANS_TIMED_OUT);

    rc = srr_collect_reply(&ep, tid2, &actual_len, &err);
    assert(rc == -2); /* Timed out */
    assert(srr_poll_transaction(&ep, tid2) == SRR_TRANS_UNUSED);

    /* Test cancellation */
    uint64_t tid3 = srr_begin_request(
        &ep, 1, 1, "CANCEL", 6,
        client_reply_buf, sizeof(client_reply_buf),
        500, now_ms
    );
    assert(tid3 > 0);
    assert(srr_poll_transaction(&ep, tid3) == SRR_TRANS_PENDING);
    rc = srr_cancel_transaction(&ep, tid3);
    assert(rc == 0);
    assert(srr_poll_transaction(&ep, tid3) == SRR_TRANS_UNUSED);

    printf("  Embedded async client & timeouts verified successfully.\n");
}

int main(void) {
    printf("=========================================\n");
    printf("SRR Embedded Profile Unit Test Suite\n");
    printf("=========================================\n");

    test_embedded_service_dispatch();
    test_embedded_pulses();
    test_embedded_async_client_and_timeouts();

    printf("\nAll embedded profile tests PASSED!\n");
    return 0;
}
